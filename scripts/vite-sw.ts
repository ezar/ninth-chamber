/**
 * The service worker (spec §14 "PWA"), generated at build time as dist/sw.js.
 *
 * - Versioned by a hash of everything the build ships (bundle file names,
 *   which carry content hashes, and the contents of public/), so any change
 *   installs a new worker whose activation drops the old caches.
 * - Pages are network-first: online, a deploy is always picked up. Hashed bundles (/assets/) are cache-first, which
 *   can never be stale since a new build has new names. Other files (models,
 *   textures, audio) are served from the cache and refreshed behind it.
 * - The whole game (engine, every chamber, its models, textures and sounds) is
 *   precached on install, a few files at a time, resuming where an install cut
 *   short stopped; the page goes in last, so a cache that holds it is complete.
 *   The music follows once the worker runs, when the page asks (cache-extras).
 * - Offline, a page load starts the newest build that is wholly cached, and
 *   files are looked up in complete builds first: a page never meets a build
 *   it does not belong to, which would leave chambers missing (the page is
 *   network first, so online it may already be a build still downloading).
 * - Streamed music asks for byte ranges, answered from the cached file.
 * - A new worker waits for open tabs to close instead of taking over a game
 *   in progress, so a running page never mixes two builds. The page offers
 *   the update on the title and in the pause menu, and only then asks the
 *   waiting worker to take over (src/ui/service-worker.ts).
 */
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import type { Plugin } from 'vite';

/** Public files precached on install: the whole game but the music. */
export const PRECACHE_PUBLIC = [
  /^audio\/(?!music\/).*\.webm$/,
  /^models\/.*\.glb$/,
  /^anim\/.*\.json$/,
  /^textures\//,
  /^basis\/.*\.(js|wasm)$/,
  /^levels\//,
  /^icons\//,
];

/** Public files cached after install, in the background: the music (most of the download). */
export const EXTRAS_PUBLIC = [/^audio\/music\/.*\.webm$/];

function walk(dir: string): string[] {
  const out: string[] = [];
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) out.push(...walk(path));
    else out.push(path);
  }
  return out;
}

/** The worker's source for a version, its precache list and the files it caches after (URLs relative to the worker). */
export function serviceWorkerSource(
  version: string,
  precache: readonly string[],
  extras: readonly string[] = [],
): string {
  return `// Generated by scripts/vite-sw.ts. Do not edit.
const VERSION = ${JSON.stringify(version)};
const CACHE = 'nc-' + VERSION;
const PRECACHE = ${JSON.stringify(precache)};
const EXTRAS = ${JSON.stringify(extras)};
const SHELL = new URL('./', self.location).href;
const abs = (u) => new URL(u, self.location).href;

const broadcast = (message) =>
  self.clients
    .matchAll({ includeUncontrolled: true, type: 'window' })
    .then((list) => list.forEach((c) => c.postMessage(message)));

// Downloads what the cache does not hold yet, a few at a time (an install cut short resumes
// where it stopped). The page goes in last: a cache that holds it holds its whole build.
async function precache() {
  const cache = await caches.open(CACHE);
  const have = new Set((await cache.keys()).map((r) => r.url));
  const files = PRECACHE.map(abs).filter((u) => u !== SHELL);
  const queue = files.filter((u) => !have.has(u));
  const total = files.length;
  let done = total - queue.length;
  const fetchOne = async () => {
    for (let url = queue.shift(); url !== undefined; url = queue.shift()) {
      const r = await fetch(url, { cache: 'no-cache' });
      if (!r.ok) throw new Error(url + ': HTTP ' + r.status);
      await cache.put(url, r);
      done++;
      broadcast({ type: 'nc-precache', done, total });
    }
  };
  await Promise.all([fetchOne(), fetchOne(), fetchOne(), fetchOne()]);
  const page = await fetch(SHELL, { cache: 'no-cache' });
  if (!page.ok) throw new Error('page: HTTP ' + page.status);
  await cache.put(SHELL, page);
  broadcast({ type: 'nc-precache', done: total, total });
}

// The music, after the build is safe: one file at a time, skipping what is already there.
async function cacheExtras() {
  const cache = await caches.open(CACHE);
  for (const url of EXTRAS.map(abs)) {
    if (await cache.match(url, { ignoreVary: true })) continue;
    const r = await fetch(url).catch(() => null);
    if (!r || !r.ok) return;
    await cache.put(url, r);
  }
}

self.addEventListener('install', (event) => {
  event.waitUntil(precache());
});

self.addEventListener('message', (event) => {
  // The page asks a waiting worker to take over only when the player chooses to update
  // (on the title or in the pause menu, never in the middle of play).
  if (event.data === 'take-over') self.skipWaiting();
  else if (event.data === 'cache-extras') event.waitUntil(cacheExtras());
  // The page asks which build answers it offline (workers before this one never reply).
  else if (event.data === 'version' && event.ports[0]) event.ports[0].postMessage(VERSION);
});

self.addEventListener('activate', (event) => {
  // Older builds go; a newer one still downloading keeps what it has.
  event.waitUntil(
    caches
      .keys()
      .then((keys) => {
        const own = keys.indexOf(CACHE);
        return Promise.all(keys.filter((k, i) => k.startsWith('nc-') && i < own).map((k) => caches.delete(k)));
      })
      .then(() => self.clients.claim()),
  );
});

// The caches to look in: complete builds first, newest first, then any still downloading.
let order = null;
async function searchOrder() {
  if (!order) {
    const keys = (await caches.keys()).filter((k) => k.startsWith('nc-')).reverse();
    const done = await Promise.all(keys.map((k) => caches.open(k).then((c) => c.match(SHELL, { ignoreVary: true })).then((r) => !!r)));
    order = [...keys.filter((k, i) => done[i]), ...keys.filter((k, i) => !done[i])];
  }
  return order;
}
// Vary is ignored: the files are static, and a page's request carries headers (Origin) the
// worker's own download did not, which some servers name in Vary.
async function lookup(request) {
  for (const k of await searchOrder()) {
    const r = await (await caches.open(k)).match(request, { ignoreVary: true });
    if (r) return r;
  }
  return undefined;
}

const put = (request, response) => {
  if (response.ok && response.status === 200) {
    const copy = response.clone();
    caches.open(CACHE).then((c) => c.put(request, copy));
  }
  return response;
};

// Streamed music asks for byte ranges: answered from the whole file once it is cached.
async function ranged(request) {
  const cached = await lookup(request.url);
  if (!cached) return fetch(request);
  const blob = await cached.blob();
  const m = /bytes=(\\d*)-(\\d*)/.exec(request.headers.get('range') || '');
  const size = blob.size;
  let start = m && m[1] ? Number(m[1]) : 0;
  let end = m && m[2] ? Number(m[2]) : size - 1;
  if (m && !m[1] && m[2]) {
    start = Math.max(0, size - Number(m[2]));
    end = size - 1;
  }
  end = Math.min(end, size - 1);
  if (start > end) return new Response(null, { status: 416, headers: { 'Content-Range': 'bytes */' + size } });
  return new Response(blob.slice(start, end + 1), {
    status: 206,
    headers: {
      'Content-Type': cached.headers.get('Content-Type') || 'application/octet-stream',
      'Content-Range': 'bytes ' + start + '-' + end + '/' + size,
      'Content-Length': String(end - start + 1),
      'Accept-Ranges': 'bytes',
    },
  });
}

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  if (request.mode === 'navigate') {
    // Network first: a deploy is never hidden behind the cache. Offline, the newest build
    // that is wholly cached starts, so every chamber it names is there.
    order = null;
    const game = url.pathname === new URL(SHELL).pathname || url.pathname.endsWith('/index.html');
    event.respondWith(
      fetch(request).catch(async () => (!game && (await lookup(request))) || (await lookup(SHELL)) || Response.error()),
    );
    return;
  }
  if (url.pathname.endsWith('/sw.js')) return;
  if (request.headers.has('range')) {
    event.respondWith(ranged(request));
    return;
  }
  const hashed = url.pathname.includes('/assets/');
  event.respondWith(
    lookup(request).then((cached) => {
      const network = fetch(request).then((r) => put(request, r));
      if (cached) {
        // Content-hashed bundles never change; other files refresh behind the cached copy.
        if (!hashed) event.waitUntil(network.catch(() => undefined));
        return cached;
      }
      return network;
    }),
  );
});
`;
}

/**
 * Critical assets the page asks for as soon as the HTML arrives, in parallel
 * with the engine's JavaScript, instead of after it has run.
 */
export const PRELOAD = [{ href: './models/nora.glb', as: 'fetch' }] as const;

/** Adds the preload links to index.html. */
export function preloadPlugin(): Plugin {
  return {
    name: 'ninth-chamber-preload',
    transformIndexHtml: () =>
      PRELOAD.map((p) => ({
        tag: 'link',
        attrs: { rel: 'preload', href: p.href, as: p.as, crossorigin: 'anonymous' },
        injectTo: 'head' as const,
      })),
  };
}

/** Emits sw.js with the build's version and precache list. */
export function serviceWorkerPlugin(root: string): Plugin {
  return {
    name: 'ninth-chamber-sw',
    apply: 'build',
    generateBundle(_options, bundle) {
      const publicDir = join(root, 'public');
      const files = walk(publicDir).map((p) => relative(publicDir, p).split(sep).join('/'));
      const hash = createHash('sha256');
      const built = Object.keys(bundle)
        .filter((f) => !f.endsWith('.map'))
        .sort();
      for (const f of built) hash.update(f);
      for (const f of files.sort()) hash.update(f).update(readFileSync(join(publicDir, f)));
      const version = hash.digest('hex').slice(0, 12);
      const precache = [
        './',
        ...built.filter((f) => f !== 'index.html' && !f.endsWith('.txt')).map((f) => `./${f}`),
        ...files.filter((f) => PRECACHE_PUBLIC.some((re) => re.test(f))).map((f) => `./${f}`),
      ];
      const extras = files.filter((f) => EXTRAS_PUBLIC.some((re) => re.test(f))).map((f) => `./${f}`);
      this.emitFile({
        type: 'asset',
        fileName: 'sw.js',
        source: serviceWorkerSource(version, precache, extras),
      });
    },
  };
}
